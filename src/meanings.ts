const MAJOR_COUNT = MAJOR_NAMES_JA.length;
const minorRank = (card: Card) => (card.id - MAJOR_COUNT) % RANK_NAMES_JA.length;

/** カードの日本語名。id の並びは Rust の Deck::new() に従う。 */
export function cardNameJa(card: Card): string {
  if (card.suit === "MajorArcana") return MAJOR_NAMES_JA[card.id];
  return `${SUIT_NAMES_JA[card.suit]}の${RANK_NAMES_JA[minorRank(card)]}`;
}

/** 正位置・逆位置の意味 (向きに関係なく両方)。 */
export function cardMeaning(card: Card): Meaning {
  if (card.suit === "MajorArcana") return MAJOR_MEANINGS[card.id];
  return MINOR_MEANINGS[card.suit][minorRank(card)];
}

/** カードの向きに応じた意味。 */
export function currentMeaning(card: Card): string {
  const meaning = cardMeaning(card);
  return card.is_reversed ? meaning.reversed : meaning.upright;
}
